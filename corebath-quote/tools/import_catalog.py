#!/usr/bin/env python3
"""Convert the CoreBath package product list (.xlsx) into assets/cbq-catalog.js.

Usage:
    python3 tools/import_catalog.py path/to/CoreBath_Package_Product_List.xlsx

Reads the "All Products" sheet (Brand, Package, Sl, Item, Qty, Product, SKU,
Unit price, Line total, Price basis, Link, Notes). Re-run it whenever you
update prices in the workbook, then re-upload assets/cbq-catalog.js.
"""
import json
import sys
from pathlib import Path

import openpyxl

# Sl number in the workbook -> stable item key + role.
# role "fixture" = what the customer sees and picks.
# role "concealed" = in-wall / connection parts the engine matches automatically.
ITEMS = {
    1: ("ewc", "fixture", "EWC (wall-hung WC)"),
    2: ("basin", "fixture", "Wash basin"),
    3: ("basin_mixer", "fixture", "Tall boy basin mixer"),
    4: ("diverter_trim", "fixture", "Diverter (exposed trim)"),
    5: ("waste_coupling", "concealed", "Waste coupling"),
    6: ("bottle_trap", "concealed", "Bottle trap"),
    7: ("angle_valve", "concealed", "Angle valve"),
    8: ("health_faucet", "fixture", "Health faucet"),
    9: ("bath_spout", "fixture", "Bath spout"),
    10: ("diverter_body", "concealed", "Concealed diverter body"),
    11: ("hand_shower", "fixture", "Hand shower"),
    12: ("sliding_rail", "fixture", "Sliding rail"),
    13: ("flexi_pipe", "concealed", "Shower flexi pipe 1.5m"),
    14: ("braided_hose", "concealed", "Braided connection hose"),
    15: ("floor_grating", "fixture", "Floor drain / grating"),
    16: ("concealed_cistern", "concealed", "Concealed cistern + flush plate"),
    17: ("stop_cock", "concealed", "Concealed stop cock"),
}
PKG = {"Core Essential": "essential", "Core Signature": "signature", "Core Luxe": "luxe"}


def clean(v):
    if v is None:
        return None
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    s = str(v).strip()
    return s or None


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb["All Products"]
    products = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        brand, pkg, sl = row[0], row[1], row[2]
        if not brand or pkg not in PKG or sl not in ITEMS:
            continue
        key, role, label = ITEMS[sl]
        name = clean(row[5]) or label
        price = row[7]
        included = price == 0 or (name or "").lower().startswith("included")
        products.append({
            "id": f"{brand.lower()}-{PKG[pkg]}-{key}",
            "brand": brand,
            "pkg": PKG[pkg],
            "key": key,
            "role": role,
            "qty": int(row[4] or 1),
            "name": name,
            "sku": clean(row[6]),
            "price": None if (price is None or included) else float(price),
            "included": bool(included),
            "basis": clean(row[9]),
            "link": clean(row[10]),
            "notes": clean(row[11]),
        })
    items = [{"key": k, "role": r, "label": l, "sl": sl} for sl, (k, r, l) in ITEMS.items()]
    out = Path(__file__).resolve().parent.parent / "assets" / "cbq-catalog.js"
    body = json.dumps({"items": items, "products": products}, ensure_ascii=False, indent=1)
    out.write_text(
        "/* Generated by tools/import_catalog.py from the CoreBath product list. Do not edit by hand. */\n"
        "(function (g) { g.CBQ = g.CBQ || {}; g.CBQ.catalog = " + body + "; })"
        "(typeof window !== 'undefined' ? window : globalThis);\n",
        encoding="utf-8",
    )
    priced = sum(1 for p in products if p["price"] is not None)
    print(f"Wrote {out} - {len(products)} products, {priced} priced, "
          f"{sum(p['included'] for p in products)} included-in-set, "
          f"{len(products) - priced - sum(p['included'] for p in products)} still to price")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
